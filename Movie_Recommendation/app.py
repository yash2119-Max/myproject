"""## Combine tags per movie"""

tags_grouped = tags.groupby("movieId")["tag"].apply(lambda x: " ".join(x.dropna().astype(str))).reset_index()

"""## Merge movies + tags"""

content_data=pd.merge(movies, tags_grouped, on="movieId", how="left")

content_data["tag"]=content_data["tag"].fillna("")

#create final feature
content_data["content"] = content_data["genres"] + " " + content_data["tag"]

from sklearn.feature_extraction.text import TfidfVectorizer

tfidf = TfidfVectorizer(stop_words="english")
matrix = tfidf.fit_transform(content_data["content"])

"""## Compute Similarity"""

from sklearn.metrics.pairwise import cosine_similarity
similarity = cosine_similarity(matrix)

"""## Build index mapping"""

indices = pd.Series(content_data.index, index=content_data["title"]).drop_duplicates()

##Recommendation function
def recommend_content(movie_title):
    if movie_title not in indices:
        return "Movie not found"

    idx = indices[movie_title]

    sim_scores = list(enumerate(similarity[idx]))
    sim_scores = sorted(sim_scores, key=lambda x: x[1], reverse=True)

    sim_scores = sim_scores[1:6]

    movie_indices = [i[0] for i in sim_scores]

    return content_data["title"].iloc[movie_indices]

recommend_content("Toy Story (1995)")

