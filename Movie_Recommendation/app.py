def hybrid_recommend(movie_name, top_n=10):
    collab = list(recommend(movie_name).index)
    content = list(recommend_content(movie_name))

    # Combine recommendations
    hybrid = []

    for movie in collab:
        if movie not in hybrid:
            hybrid.append(movie)

    for movie in content:
        if movie not in hybrid:
            hybrid.append(movie)

    return hybrid[:top_n]

